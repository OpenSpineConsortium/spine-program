#!/usr/bin/env python
"""Before/after of two CHK-9 reports (tools/leak_check.py chk9): the verdict counts, every row whose verdict moved,
and the substituted rows one by one with the pair that decides them.

    python chk9_diff.py before/chk9_report.json after/chk9_report.json quoted_results_cv_v9.json --out CHK9_DIFF.md
"""
import argparse
import json
from collections import Counter

COUNTS = ("n_rows", "n_held_out", "n_seen", "n_unresolved", "n_no_eval_keys", "n_declared", "n_not_applicable")


def short_why(p):
    if p.get("why"):
        return p["why"][:300]
    parts = []
    for i in p.get("instances") or []:
        if i["verdict"] == "HELD OUT":
            continue
        tag = i["checkpoint"].split("/")[-1] + (f"#{i['fold']}" if i.get("fold") else "")
        if i.get("overlap"):
            parts.append(f"{tag}: {i['overlap']} of {i['n_eval_keys']} seen at {i.get('overlap_at')}")
        elif i.get("unresolved"):
            parts.append(f"{tag}: unresolved {i.get('unresolved_what')}")
        else:
            parts.append(f"{tag}: {i.get('n_eval_unkeyed')} unkeyed")
    return "; ".join(parts)[:300]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("before")
    ap.add_argument("after")
    ap.add_argument("quoted_cv_v9")
    ap.add_argument("--out", required=True)
    ap.add_argument("--json", default=None)
    a = ap.parse_args()
    B, A = json.load(open(a.before, encoding="utf-8")), json.load(open(a.after, encoding="utf-8"))
    Q = json.load(open(a.quoted_cv_v9, encoding="utf-8"))
    subs = list(Q.get("substituted_rows") or [])
    rb = {r["id"]: r for r in B["rows"]}
    ra = {r["id"]: r for r in A["rows"]}
    moved = [(i, rb[i]["verdict"], ra[i]["verdict"]) for i in rb if i in ra and rb[i]["verdict"] != ra[i]["verdict"]]
    moved_outside = [m for m in moved if m[0] not in subs]
    sub_rows = []
    for i in subs:
        b, r = rb.get(i), ra.get(i)
        pairs = [(p["checkpoint"], p["eval_set"], p["verdict"], short_why(p)) for p in (r or {}).get("pairs") or []]
        n_inst = sum(len(p.get("instances") or []) for p in (r or {}).get("pairs") or [])
        n_keys = max([i2.get("n_eval_keys") or 0 for p in (r or {}).get("pairs") or [] for i2 in p.get("instances") or []] or [0])
        sub_rows.append(dict(id=i, before=b["verdict"] if b else None, after=r["verdict"] if r else None,
                             pairs=pairs, n_instances=n_inst, max_eval_keys=n_keys,
                             inventory=(r or {}).get("inventory_verdict")))
    trans = Counter((s["before"], s["after"]) for s in sub_rows)
    L = ["# CHK-9 before and after the cv_v9 substitution (generated by closure/chk9_cv_v9/chk9_diff.py)\n",
         f"\nInputs: before `{a.before}`, after `{a.after}`, rows substituted `{a.quoted_cv_v9}` ({len(subs)} rows).\n",
         "\n| count | before | after |\n|---|---:|---:|\n"]
    for c in COUNTS:
        L.append(f"| {c} | {B.get(c)} | {A.get(c)} |\n")
    L.append(f"\nCLEAN (HELD OUT) {B['n_held_out']} -> {A['n_held_out']}; LEAKED (SEEN) {B['n_seen']} -> {A['n_seen']}; "
             f"UNRESOLVED {B['n_unresolved']} -> {A['n_unresolved']}; NO EVAL KEYS {B['n_no_eval_keys']} -> {A['n_no_eval_keys']}; "
             f"N/A {B['n_not_applicable']} -> {A['n_not_applicable']}.\n")
    L.append(f"\nRows whose verdict moved: {len(moved)}; of them outside the substituted set: {len(moved_outside)}"
             + (" " + json.dumps(moved_outside) if moved_outside else "") + ".\n")
    L.append("\nSubstituted rows, transitions: " + "; ".join(f"{k[0]} -> {k[1]}: {v}" for k, v in sorted(trans.items(), key=lambda kv: -kv[1])) + ".\n")
    L.append("\n| row | inventory | before | after | pairs (checkpoint on set: verdict) | instances | eval keys |\n|---|---|---|---|---|---:|---:|\n")
    for s in sub_rows:
        pr = "; ".join(f"{c} on {e}: {v}" + (f" ({w})" if v != "HELD OUT" and w else "") for c, e, v, w in s["pairs"])
        L.append(f"| `{s['id']}` | {s['inventory']} | {s['before']} | {s['after']} | {pr.replace('|', '/')} | {s['n_instances']} | {s['max_eval_keys']} |\n")
    still = [s for s in sub_rows if s["after"] != "HELD OUT"]
    L.append(f"\nSubstituted rows not HELD OUT after: {len(still)}"
             + ("".join(f"\n- `{s['id']}` {s['after']}: " + "; ".join(f"{c} on {e}: {v} {w}" for c, e, v, w in s["pairs"] if v != "HELD OUT") for s in still) if still else "") + "\n")
    da = A.get("disagree_with_inventory") or []
    L.append(f"\nCHK-9 vs the hand inventory (EVALUATORS.md) after: {A.get('n_disagree_with_inventory')} rows disagree"
             + ("; " + ", ".join(f"`{d['id']}` chk9 {d['chk9']} / inventory {d['inventory']}" for d in da[:40]) if da else "") + ".\n")
    open(a.out, "w", encoding="utf-8").write("".join(L))
    if a.json:
        json.dump(dict(before={c: B.get(c) for c in COUNTS}, after={c: A.get(c) for c in COUNTS}, moved=moved,
                       moved_outside_substituted=moved_outside, substituted=sub_rows,
                       transitions={f"{k[0]} -> {k[1]}": v for k, v in trans.items()},
                       inputs=dict(before=B.get("inputs"), after=A.get("inputs"))),
                  open(a.json, "w", encoding="utf-8"), indent=1)
    print("".join(L[:12]))


if __name__ == "__main__":
    main()
