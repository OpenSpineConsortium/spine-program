"""The sources that may not enter a corpus, a list, a bank or a probe -- and a gate that RAISES rather than drops.

WHY THIS EXISTS. Greg, 2026-09-23, on seeing Mendeley separated from BUU-LSPINE at 0.919 in the corpus manifold:
*"Mendeley is like 75 % a subset of BUU, false result -- make it so either that portion cannot make its way into
the pipeline or just exclude the entire dataset."* He is right on both counts. The measured overlap is larger than
his estimate: **500 of 584 films (86 %) are re-encodings of BUU films already in training, and their filenames ARE
the BUU identifiers** (tools/build_review_pack.py). A classifier separating "Mendeley" from "BUU" is therefore
separating a JPEG re-encoding from its own original -- the 0.919 is the artefact, not a finding.

A silent drop is not enough. A source excluded in one builder and forgotten in another is how FluoroCap panels and
duplicate COBRA frames reached training lists before. Every builder calls `assert_clean` and gets an exception
naming the offending path, so an exclusion cannot be lost by editing one glob.

    from excluded_sources import assert_clean, is_excluded, REASONS
    assert_clean(paths, where="devcorpus lists")     # raises ExcludedSource on the first hit
    keep = [p for p in paths if not is_excluded(p)]  # only where a filter is genuinely wanted

Adding a source here is a scientific decision and takes a written reason. Removing one takes the same.
"""
from __future__ import annotations

import os
import re

# token -> why. The token is matched case-insensitively against the whole path, so it catches
# mendeley_716, mendeley_drr, mendeley_fov96_ctx and the raw extract alike.
REASONS = {
    "mendeley": (
        "86 % of it (500 of 584 films) is BUU-LSPINE re-encoded, filenames are the BUU identifiers, and its levels "
        "were generated by counting up from the most caudal body rather than read. The non-BUU remainder carries the "
        "same counting-inferred labels, so it adds no independent truth; what distinguishes it from BUU in a probe "
        "is JPEG re-encoding. Excluded entirely (Greg, 2026-09-23)."
    ),
    "fluorocap": (
        "Reproductions of published figures, not fluoroscopy: 72.8 % of panels have zero pixel residual against the "
        "source figure. Dropped from every training set by PI decision (2026-09-23); may serve as an annotated real-"
        "film TEST set only, which is loaded explicitly and never through a corpus glob."
    ),
}

# paths that are allowed through even though they match a token: the explicit test-only loads
ALLOW = (
    re.compile(r"fluorocap[^/\\]*test", re.I),
)


class ExcludedSource(RuntimeError):
    pass


def reason_for(path) -> str | None:
    """The reason this path is excluded, or None."""
    s = str(path).replace("\\", "/").lower()
    if any(a.search(s) for a in ALLOW):
        return None
    for token, why in REASONS.items():
        if token in s:
            return why
    return None


def is_excluded(path) -> bool:
    return reason_for(path) is not None


def assert_clean(paths, where="this corpus") -> None:
    """Raise on the first excluded path. `paths` may be strings, Paths, or dicts with a 'path'/'glob' key."""
    def _p(x):
        if isinstance(x, dict):
            return x.get("path") or x.get("glob") or x.get("dir") or ""
        return x
    for x in paths:
        p = _p(x)
        why = reason_for(p)
        if why:
            raise ExcludedSource(f"{where}: {os.path.basename(str(p)) or p} comes from an excluded source.\n  {why}\n"
                                 f"  Full path: {p}\n"
                                 f"  If this is deliberate, say so in tools/excluded_sources.py -- do not bypass it here.")


def filter_paths(paths, where="this corpus", announce=True):
    """Keep what is allowed; print what was removed and why, once per source."""
    kept, removed = [], {}
    for p in paths:
        why = reason_for(p)
        if why:
            removed.setdefault(why, 0)
            removed[why] += 1
        else:
            kept.append(p)
    if announce and removed:
        for why, n in removed.items():
            print(f"  {where}: dropped {n} path(s) -- {why}", flush=True)
    return kept


def _self_test() -> int:
    bad = ["/rs/data/films/mendeley_716/x.jpg", "~/mendeley_drr/img/a.npy", "~/mendeley_fov96_ctx/crop.png",
           "/data/FluoroCap/panels/p1.png"]
    good = ["/rs/data/realxray/carmlspine/images/test/case1_AP.png", "~/buu_yolo/images/train/1234.png",
            "/data/fluorocap_test_annotated/p1.png"]
    for b in bad:
        assert is_excluded(b), f"should be excluded: {b}"
    for g in good:
        assert not is_excluded(g), f"should be allowed: {g}"
    try:
        assert_clean(bad, where="self-test")
    except ExcludedSource as e:
        assert "excluded source" in str(e)
    else:
        raise AssertionError("assert_clean did not raise")
    assert len(filter_paths(bad + good, announce=False)) == len(good)
    print("EXCLUDED_SOURCES_SELF_TEST_OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(_self_test())
