"""The CNS closing video's frames: a lateral C-arm pan from the sacrum to C2 over one whole-spine CT.

One ENHANCE.PET CT that the level encoder never saw (the set landed a month after v9 trained), normal by its
own labels (C1 to L5 and the sacrum, no L6), with the thinnest slices of the set. The CT is projected
laterally, orthographically, as one tall panorama that follows the spine; the panorama is made to look like a
real X-ray by FLUX.2 klein-9B as released, zero-shot, the edit FluXray ran (4 steps, guidance 1.0, bfloat16),
in overlapping tiles blended across the overlap, with FluXray's prompt less its sentence asking for clinical
text, so no letters are drawn into the image. The pan is then cut from the edited panorama: one 1024-pixel
frame of 260 mm at 30 frames a second, opening on the sacrum and L5, centred on the spine as an operator follows it, with the
C-arm's round field, its vignette and fresh quantum noise in every frame. Cutting every frame from one edit
keeps the anatomy still from frame to frame, where editing each frame alone would make it boil.

The shoulders are what hide the upper thoracic spine in a true lateral, so three things are done to the CT
before it is projected, none of which draws an edge in the frame. The shoulder girdle and arm bones are taken
down to soft tissue (bone to 40 HU, air and fat left alone). From T6 up the ray is cut to a slab about the spine,
170 mm either side at T6, 110 mm at T3 and 80 mm from T1 up, which leaves the humeral heads, the arms and the
shoulders' bulk out and the lungs in; the slab runs along the ray and is cut after the body is found, so the chest
stays whole. And the vertebrae from C5 to T5 are weighted up, C7 and T1 by 60 per cent, as a swimmer's view lifts
them, and T6 to T12, behind the heart and the diaphragm's dome, by a fifth. The first cut
(an arm's reach of 45 mm taken out of the body, v21) punched holes in the chest that FLUX filled black, and T1 to
T4 went unseen; the second (a 75 mm slab before the body was found) cut the chest wall loose from the spine, slice
by slice, and banded the heart; with the slab after the body and only C7 to T5 lifted (run 6) the count reached
T2, and with the shoulders cut to 80 mm but the mid thoracic unlifted (run 7) it broke at T10. These settings
(run 8) are the first whose boxes the linker counts unbroken from L5 to C3.

    python pan_render.py OUT [SUBJECT]

Writes OUT/raw.png and OUT/flux_s<seed>.png (the panoramas), OUT/frames/f####.png, OUT/pan.json (the subject,
the scale, each frame's centre in panorama pixels, each vertebra's centre in panorama pixels for reference
only), and OUT/flux.json (the recipe and the time each tile took).
"""
from __future__ import annotations

import json
import math
import sys
import time
from pathlib import Path

import numpy as np
import nibabel as nib
from scipy import ndimage

CT = Path("/rs/rs_grp_oschome/go2432/data/aws_enhance_pet_ct/raw")
LABELS = Path("/rs/rs_grp_oschome/go2432/data/aws_enhance_pet_labels/raw")
KLEIN = "/rs/rs_grp_oschome/go2432/data/hf_flux2_klein_9b/raw"
PX = 0.254                      # mm a pixel, panorama and frames alike
FRAME = 1024                    # 260 mm square, the round field 240 mm across
FPS, HOLD, PAN, REST = 30, 45, 420, 30   # frames a second; held on the sacrum; the pan; held on C2
HALF_MM = FRAME * PX / 2
ARM_BONES = (1, 2, 9, 10, 11, 12, 13, 14, 19, 20, 30, 31)   # carpals, fingers, humeri, metacarpals, radii, ulnae
GIRDLE = (3, 4, 21, 22)                                      # clavicles, scapulae
SLAB = (("T6", 170.0), ("T3", 110.0), ("T1", 80.0))          # mm either side of the spine, by level, eased between
LIFT = {"C5": 1.3, "C6": 1.5, "C7": 1.6, "T1": 1.6, "T2": 1.5, "T3": 1.5, "T4": 1.5, "T5": 1.25,   # under the shoulders
        **{f"T{k}": 1.2 for k in range(6, 13)}}                                                    # behind heart and dome
LEVELS = {i: n for i, n in enumerate([f"C{k}" for k in range(1, 8)] + [f"T{k}" for k in range(1, 13)]
                                     + [f"L{k}" for k in range(1, 6)], start=1)}
SACRUM, L6 = 28, 25
TILE, OVERLAP = 1536, 512
SEEDS = (0, 1)
PROMPT = ("Make this synthetic X-ray (generated by a projection through a CT) look like a real X-ray. "
          "The generated image should preserve ALL anatomical structure, no shape changes at all. "
          "Do not add any text, letters, numbers or markers to the image. "
          "Also, add some realistic X-ray textures to the image. "
          "The output must be well registered with the input.")


def thin_candidates(limit=80):
    rows = []
    for path in sorted(CT.glob("*.nii.gz")):
        header = nib.load(str(path)).header
        dz, nz = float(header.get_zooms()[2]), header.get_data_shape()[2]
        if dz <= 1.25 and dz * nz >= 650:
            rows.append((dz, path.name[:4]))
    return [s for _, s in sorted(rows)][:limit]


def canonical(path):
    image = nib.as_closest_canonical(nib.load(str(path)))
    return np.asarray(image.dataobj), np.array(image.header.get_zooms()[:3], float)


def normal_spine(subject):
    """C1 to L5 and the sacrum, no L6, and no metal (a joint replacement or fixation would stand in the field)."""
    labels, _ = canonical(LABELS / "Vertebrae" / f"{subject}.nii.gz")
    ids, counts = np.unique(labels, return_counts=True)
    present = {int(i) for i, c in zip(ids, counts) if c > 500}
    if not (set(LEVELS) | {SACRUM} <= present and L6 not in present):
        return False
    hu, _ = canonical(CT / f"{subject}.nii.gz")
    below = int(np.nonzero((labels == 2).any(axis=(0, 1)))[0].min())    # under C2: teeth and fillings are no matter
    return int((np.asarray(hu[:, :, :below]) > 3000).sum()) < 200


def pick(subject=None):
    if subject:
        return subject
    for s in thin_candidates():
        if normal_spine(s):
            return s
    raise SystemExit("no thin-slice normal whole spine among the candidates")


def spine_track(vert):
    """The spine's (x, y) voxel in every axial slice, carried to the slices no vertebra reaches."""
    nz = vert.shape[2]
    known = {}
    for k in range(nz):
        idx = np.nonzero(vert[:, :, k] > 0)
        if idx[0].size:
            known[k] = (idx[0].mean(), idx[1].mean())
    ks = np.array(sorted(known))
    xs = np.interp(np.arange(nz), ks, [known[k][0] for k in ks])
    ys = np.interp(np.arange(nz), ks, [known[k][1] for k in ks])
    return np.stack([xs, ys], 1)


def body_mask(hu, vert):
    """The patient alone in every slice: tissue above -400 HU, the part that holds the spine once thin bridges
    (a hand on the chin, the table's pad) are eroded away."""
    keep = np.zeros(hu.shape, bool)
    track = spine_track(vert)
    for k in range(hu.shape[2]):
        m = hu[:, :, k] > -400
        core = ndimage.binary_erosion(ndimage.binary_opening(m, iterations=2), iterations=6)
        lab, n = ndimage.label(core)
        if n == 0:
            continue
        x, y = np.clip(np.rint(track[k]).astype(int), 0, np.array(m.shape) - 1)
        pick = lab[x, y]
        if pick == 0:
            pick = 1 + int(np.argmax(ndimage.sum(core, lab, range(1, n + 1))))
        part = ndimage.binary_dilation(lab == pick, iterations=6) & m
        keep[:, :, k] = ndimage.binary_fill_holes(part)
    return keep


def centres(vert, zoom):
    out = {}
    for i, name in LEVELS.items():
        c = ndimage.center_of_mass(vert == i)
        out[name] = (np.array(c) * zoom).tolist()
    zs = np.nonzero(vert == SACRUM)
    top = zs[2].max()
    upper = (vert == SACRUM) & (np.arange(vert.shape[2])[None, None, :] >= top - 35 / zoom[2])
    out["S1"] = (np.array(ndimage.center_of_mass(upper)) * zoom).tolist()
    return out


def attenuation(hu):
    mu = 0.02 * np.clip(1 + hu / 1000.0, 0, None)
    bone = np.clip((hu - 150) / 1000.0, 0, 1)
    return mu * (1 + 0.5 * bone)


def slab(hu, vert, zoom, pts):
    """Air outside the slab about the spine, its half-width set at each level of SLAB and eased between, held
    below the first and above the last, each slice about the spine's own centre in that slice."""
    track = spine_track(vert)
    z = (np.arange(hu.shape[2]) + 0.5) * zoom[2]
    half = np.interp(z, [pts[n][2] for n, _ in SLAB], [w for _, w in SLAB])
    half = ndimage.gaussian_filter1d(half, 15 / zoom[2])
    x = (np.arange(hu.shape[0]) + 0.5) * zoom[0]
    for k in range(hu.shape[2]):
        out = np.abs(x - (track[k, 0] + 0.5) * zoom[0]) > half[k]
        hu[out, :, k] = -1000.0


def soften(hu, bones):
    """The shoulder girdle and the arms as soft tissue: their bone taken down to 40 HU, air and fat left alone."""
    near = ndimage.binary_dilation(np.isin(bones, GIRDLE + ARM_BONES), iterations=2)
    hu[near] = np.minimum(hu[near], 40.0)


def lift(mu, vert):
    """The bodies under the shoulders weighted up, label by label."""
    names = {n: i for i, n in LEVELS.items()}
    for name, weight in LIFT.items():
        mu[vert == names[name]] *= weight


def project(subject):
    hu, zoom = canonical(CT / f"{subject}.nii.gz")
    hu = hu.astype(np.float32)
    vert, _ = canonical(LABELS / "Vertebrae" / f"{subject}.nii.gz")
    pts = centres(vert, zoom)
    bones = LABELS / "Peripheral-Bones" / f"{subject}.nii.gz"
    if bones.is_file():
        soften(hu, canonical(bones)[0])
    inside = body_mask(hu, vert)
    hu[~inside] = -1000.0
    slab(hu, vert, zoom, pts)
    mu = attenuation(hu)
    del hu
    lift(mu, vert)
    line = mu.sum(axis=0) * zoom[0]                              # (y, z) line integrals, mm; air adds nothing
    return line, zoom, pts, vert


def label_projection(vert):
    """Each (y, z) column's vertebra: the label with the most voxels along the ray, 0 where none."""
    ids = list(LEVELS) + [SACRUM]
    counts = np.stack([(vert == i).sum(axis=0) for i in ids])
    best = np.argmax(counts, axis=0)
    return np.where(counts.max(axis=0) > 0, np.array(ids, np.uint8)[best], 0).astype(np.uint8)


def masks(vert, zoom, out):
    """Each vertebra's mask at 1 mm, cropped to its box, with the box's corner in CT mm (x, y, z)."""
    keep = {}
    for i, name in list(LEVELS.items()) + [(SACRUM, "S")]:
        idx = np.nonzero(vert == i)
        lo = np.array([a.min() for a in idx]); hi = np.array([a.max() for a in idx]) + 1
        box = (vert[lo[0]:hi[0], lo[1]:hi[1], lo[2]:hi[2]] == i).astype(np.float32)
        iso = ndimage.zoom(box, zoom, order=1) > 0.5
        keep[name] = np.packbits(iso)
        keep[name + "_shape"] = np.array(iso.shape)
        keep[name + "_corner"] = lo * zoom
    np.savez_compressed(out / "masks.npz", **keep)


def to_pixels(line, zoom):
    """Rows superior first, columns anterior first, PX mm a pixel."""
    image = line.T[::-1, ::-1]
    return ndimage.zoom(image, (zoom[2] / PX, zoom[1] / PX), order=3)


def panorama_box(pts, shape_mm):
    zs = [p[2] for p in pts.values()]
    ys = [p[1] for p in pts.values()]
    z0, z1 = pts["S1"][2] - 60 - HALF_MM - 10, pts["C2"][2] + 10 + HALF_MM + 10
    y0, y1 = min(ys) - HALF_MM - 10, max(ys) + HALF_MM + 10
    return z0, z1, y0, y1


def crop(image, zoom, shape, box):
    """The panorama's pixels for the box (z0, z1, y0, y1) in CT mm, padded with air, sides multiples of 16."""
    z0, z1, y0, y1 = box
    zmax, ymax = shape[2] * zoom[2], shape[1] * zoom[1]
    r0, c0 = int(round((zmax - z1) / PX)), int(round((ymax - y1) / PX))
    h, w = int(math.ceil((z1 - z0) / PX / 16) * 16), int(math.ceil((y1 - y0) / PX / 16) * 16)
    out = np.zeros((h, w), np.float32)
    rs, cs = max(0, r0), max(0, c0)
    re, ce = min(image.shape[0], r0 + h), min(image.shape[1], c0 + w)
    out[rs - r0:re - r0, cs - c0:ce - c0] = image[rs:re, cs:ce]
    return out, (zmax, ymax, r0, c0)


def where(point, frame):
    zmax, ymax, r0, c0 = frame
    return [(zmax - point[2]) / PX - r0, (ymax - point[1]) / PX - c0]


def exposure(line):
    """A raw DRR as a radiograph shows it, bone bright, levelled along the spine as the C-arm's automatic
    exposure levels each frame, with the range compression and edge lift a fluoroscope's processor applies."""
    body = line > 0.15 * np.percentile(line, 99.5)
    rows = np.array([np.median(r[b]) if b.sum() > 50 else np.nan for r, b in zip(line, body)])
    rows = np.where(np.isnan(rows), np.nanmedian(rows), rows)
    rows = ndimage.gaussian_filter1d(rows, 40 / PX)
    level = (rows.mean() / rows) ** 0.75
    out = line * level[:, None]
    base = ndimage.gaussian_filter(out, 25 / PX)
    out = 0.45 * base + 2.4 * (out - base)                     # the processor's range compression and edge lift
    lo, hi = np.percentile(out[body], (0.5, 99.7))
    edge = ndimage.gaussian_filter(body.astype(np.float32), 2 / PX)
    shown = 0.06 + 0.94 * np.clip((out - lo) / (hi - lo), 0, 1)   # air in the chest dark, never a hole
    return shown * np.clip(edge * 1.6, 0, 1)


def flux(raw, out, seed, pipe, log):
    import torch
    from PIL import Image
    h, w = raw.shape
    n = max(1, math.ceil((h - TILE) / (TILE - OVERLAP)) + 1)
    starts = np.linspace(0, h - TILE, n).round().astype(int) if h > TILE else [0]
    acc, weight = np.zeros_like(raw), np.zeros_like(raw)
    for i, s in enumerate(starts):
        tile = raw[s:s + TILE]
        tick = time.time()
        picture = Image.fromarray(np.clip(np.rint(tile * 255), 0, 255).astype(np.uint8)).convert("RGB")
        edit = pipe(image=picture, prompt=PROMPT, height=tile.shape[0], width=w, num_inference_steps=4,
                    guidance_scale=1.0, generator=torch.Generator("cuda").manual_seed(seed * 100 + i)).images[0]
        edited = np.asarray(edit.convert("L"), np.float32) / 255.0
        ramp = np.ones(tile.shape[0], np.float32)
        if i > 0:
            ramp[:OVERLAP] = np.linspace(0, 1, OVERLAP)
        if i < len(starts) - 1:
            ramp[-OVERLAP:] = np.minimum(ramp[-OVERLAP:], np.linspace(1, 0, OVERLAP))
        acc[s:s + TILE] += edited * ramp[:, None]
        weight[s:s + TILE] += ramp[:, None]
        log.append({"seed": seed, "tile": i, "start": int(s), "seconds": round(time.time() - tick, 1)})
    edited = acc / np.maximum(weight, 1e-6)
    edited[raw < 0.01] = 0.0                                   # outside the body only
    save(out / f"flux_s{seed}.png", edited)
    return edited


def save(path, a):
    from PIL import Image
    Image.fromarray(np.clip(np.rint(a * 255), 0, 255).astype(np.uint8)).save(path)


def path_of(pts, frame):
    """Frame centres in panorama pixels: held at the sacrum, eased up the spine, held at C2."""
    order = ["S1"] + [f"L{k}" for k in range(5, 0, -1)] + [f"T{k}" for k in range(12, 0, -1)] + \
            [f"C{k}" for k in range(7, 1, -1)]
    at = np.array([where(pts[n], frame) for n in order])
    start, end = at[0][0] + 60 / PX, at[-1][0] - 10 / PX
    t = np.linspace(0, 1, PAN)
    ease = t * t * (3 - 2 * t)
    rows = np.concatenate([np.full(HOLD, start), start + (end - start) * ease, np.full(REST, end)])
    cols_at = ndimage.gaussian_filter1d(at[:, 1], 1.5)
    cols = np.interp(-rows, -at[:, 0], cols_at)
    return np.stack([rows, cols], 1)


def fluoro(panorama, centre, rng):
    r, c = int(round(centre[0] - FRAME / 2)), int(round(centre[1] - FRAME / 2))
    out = np.zeros((FRAME, FRAME), np.float32)
    rs, cs = max(0, r), max(0, c)
    re, ce = min(panorama.shape[0], r + FRAME), min(panorama.shape[1], c + FRAME)
    out[rs - r:re - r, cs - c:ce - c] = panorama[rs:re, cs:ce]
    yy, xx = np.mgrid[:FRAME, :FRAME] - (FRAME - 1) / 2
    rr = np.hypot(yy, xx) / (0.47 * FRAME)
    inside = out[rr < 1]
    out = out * (0.88 / max(np.percentile(inside, 98), 1e-3))
    out = ndimage.gaussian_filter(out, 0.6)
    out = out + rng.normal(0, 1, out.shape) * 0.022 * np.sqrt(np.clip(out, 0, None) + 0.05)
    out *= 1 - 0.18 * np.clip(rr, 0, 1) ** 2
    out *= np.clip((1 - rr) / 0.012, 0, 1)
    return np.clip(out, 0, 1)


def main():
    out = Path(sys.argv[1])
    (out / "frames").mkdir(parents=True, exist_ok=True)
    subject = pick(sys.argv[2] if len(sys.argv) > 2 else None)
    print("subject", subject, flush=True)
    line, zoom, pts, vert = project(subject)
    image = to_pixels(line, zoom)
    shape = (0, line.shape[0], line.shape[1])
    pano, frame = crop(image, zoom, shape, panorama_box(pts, None))
    labels = ndimage.zoom(label_projection(vert).T[::-1, ::-1], (zoom[2] / PX, zoom[1] / PX), order=0)
    labels, _ = crop(labels.astype(np.float32), zoom, shape, panorama_box(pts, None))
    from PIL import Image
    Image.fromarray(labels.astype(np.uint8)).save(out / "labels.png")
    masks(vert, zoom, out)
    del vert
    raw = exposure(pano)
    save(out / "raw.png", raw)
    import torch
    from diffusers import Flux2KleinPipeline
    pipe = Flux2KleinPipeline.from_pretrained(KLEIN, torch_dtype=torch.bfloat16)
    pipe.enable_model_cpu_offload()
    log = []
    edits = {seed: flux(raw, out, seed, pipe, log) for seed in SEEDS}
    json.dump({"model": "FLUX.2 klein-9B", "weights": KLEIN, "steps": 4, "guidance": 1.0, "dtype": "bfloat16",
               "prompt": PROMPT, "tile": TILE, "overlap": OVERLAP, "tiles": log}, open(out / "flux.json", "w"), indent=1)
    centres_px = path_of(pts, frame)
    rng = np.random.default_rng(20261102)
    for k, centre in enumerate(centres_px):
        save(out / "frames" / f"f{k:04d}.png", fluoro(edits[SEEDS[0]], centre, rng))
    json.dump({"subject": subject, "mm_per_px": PX, "frame": FRAME, "fps": FPS, "hold": HOLD, "pan": PAN,
               "rest": REST, "to_panorama": [float(v) for v in frame], "zoom": zoom.tolist(),
               "panorama": list(raw.shape), "centres": centres_px.round(1).tolist(),
               "vertebrae": {n: [round(v, 1) for v in where(p, frame)] for n, p in pts.items()}},
              open(out / "pan.json", "w"), indent=1)
    print("frames", len(centres_px), "panorama", raw.shape, flush=True)


if __name__ == "__main__":
    main()
